# Keywords: ------ :

#1 - Keywords are also called Reserved Words.
#2 - We cannot use a keyword as a variable name, function name or any other identifier
#3 - A word that already has a special meaning in Python.
#4 - In Python, keywords are case-sensitive

#Example:-----:
# if age >= 18
#      print ("you can vote")

#if → Keyword
#age → Identifier
#print → built-in function
#18 → value
# - Python understands the keyword.

# Identifiers - An identifier is simply a name that you give to something in your program.:-----:
#age = 25
#name = "Akshay"
# age and name are Identifier

#1 - Identifiers are the names used to identify a variable, function, class, module, or other objects.
#2 - They start with a letter (A-Z, a-z) or an Underscore (_) followed by zero or more letters, and digits (0-9)

# Rules for writing Identifiers:-----:

# can Use letters
# Can user numbers, but not at the beginning
# Underscore is allowed
# Do not use space
# Do not use python keywords

